export function getStoredLanguage() {
  return localStorage.getItem(STORAGE_KEY) || "en";
}

export function setStoredLanguage(language) {
  localStorage.setItem(STORAGE_KEY, language);
}

export function translate(language, key, params = {}) {
  const table = messages[language] ?? messages.en;
  const template = table[key] ?? messages.en[key] ?? key;

  return template.replace(/\{(\w+)\}/g, (_, token) => params[token] ?? `{${token}}`);
}

export function applyI18n(root, language) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = translate(language, node.dataset.i18n);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", translate(language, node.dataset.i18nPlaceholder));
  });

  document.title = translate(language, "app.title");
}

export function initLanguageSelect(select, language, onChange) {
  select.innerHTML = "";

  for (const item of languages) {
    const option = document.createElement("option");
    option.value = item.code;
    option.textContent = item.label;
    option.selected = item.code === language;
    select.append(option);
  }

  select.addEventListener("change", () => {
    const nextLanguage = select.value;
    setStoredLanguage(nextLanguage);
    onChange(nextLanguage);
  });
}
