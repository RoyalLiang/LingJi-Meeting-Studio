import { createRoot } from 'react-dom/client';
import App from './App';
import { isTauri } from '@tauri-apps/api/core';
import { RecordingWidget } from './components/RecordingWidget';
import { initializeTheme } from './native-theme';
import './styles.css';
import './workbench.css';
initializeTheme();
const desktop = isTauri();
const widgetMode = desktop && location.hash === '#recording-widget';
if (desktop) document.addEventListener('contextmenu', event => event.preventDefault());
document.documentElement.classList.toggle('webview2',desktop && /Windows/.test(navigator.userAgent));
document.documentElement.classList.toggle('recording-capsule-mode',widgetMode);
createRoot(document.getElementById('root')!).render(widgetMode ? <RecordingWidget/> : <App/>);
